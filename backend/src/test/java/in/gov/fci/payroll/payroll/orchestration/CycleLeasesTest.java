package in.gov.fci.payroll.payroll.orchestration;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import in.gov.fci.payroll.platform.error.ApiErrorCode;
import in.gov.fci.payroll.platform.error.FciException;
import java.time.Clock;
import java.time.Duration;
import java.time.Instant;
import java.time.ZoneId;
import java.time.ZoneOffset;
import java.util.List;
import java.util.Map;
import java.util.concurrent.atomic.AtomicReference;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.dao.DuplicateKeyException;
import org.springframework.jdbc.core.JdbcTemplate;

/**
 * SRS-15-28 / BR-CYC-015 (plan 05 phase 05c, D-7): the cycle lease on an in-memory copy of the DDL
 * {@code cycle_lease} and {@code cycle_lease_log} (without their foreign keys), with a clock the
 * test moves: one holder per instance, refusal naming it, take-over of an expired lease, the run's
 * own lease kept on restart, and a force-release only of the lease the request named.
 */
class CycleLeasesTest {

    private static final Instant T0 = Instant.parse("2026-10-25T06:30:00Z");
    private static final long CYCLE = 41L;

    private final AtomicReference<Instant> now = new AtomicReference<>(T0);
    private final Clock clock =
            new Clock() {
                @Override
                public ZoneId getZone() {
                    return ZoneOffset.UTC;
                }

                @Override
                public Clock withZone(ZoneId zone) {
                    return this;
                }

                @Override
                public Instant instant() {
                    return now.get();
                }
            };

    /** Set: the next lease INSERT meets this race (a competing row, or none when null). */
    private final AtomicReference<Runnable> race = new AtomicReference<>();

    private JdbcTemplate jdbc;
    private CycleLeases leases;

    @BeforeEach
    void schema() {
        org.h2.jdbcx.JdbcDataSource h2 = new org.h2.jdbcx.JdbcDataSource();
        h2.setURL("jdbc:h2:mem:cycleleases;MODE=Oracle;DB_CLOSE_DELAY=-1");
        jdbc =
                new JdbcTemplate(h2) {
                    @Override
                    public int update(String sql, Object... args) {
                        Runnable r = race.getAndSet(null);
                        if (r != null && sql.startsWith("INSERT INTO cycle_lease (")) {
                            r.run();
                        }
                        return super.update(sql, args);
                    }
                };
        jdbc.execute("DROP TABLE IF EXISTS cycle_lease");
        jdbc.execute("DROP TABLE IF EXISTS cycle_lease_log");
        jdbc.execute(
                "CREATE TABLE cycle_lease (cycle_instance_id BIGINT PRIMARY KEY, lease_action"
                        + " VARCHAR(20) NOT NULL, held_by VARCHAR(50) NOT NULL, acquired_at"
                        + " TIMESTAMP NOT NULL, heartbeat_at TIMESTAMP NOT NULL, run_id BIGINT)");
        jdbc.execute(
                "CREATE TABLE cycle_lease_log (lease_log_id BIGINT GENERATED BY DEFAULT AS IDENTITY"
                    + " PRIMARY KEY, cycle_instance_id BIGINT NOT NULL, lease_action VARCHAR(20)"
                    + " NOT NULL, held_by VARCHAR(50) NOT NULL, event_type VARCHAR(15) NOT NULL,"
                    + " event_at TIMESTAMP NOT NULL, released_by VARCHAR(50), force_release_reason"
                    + " VARCHAR(1000), approval_id BIGINT, otp_challenge_id BIGINT)");
        leases = new CycleLeases(jdbc, clock, Duration.ofMinutes(5));
    }

    private List<String> events() {
        return jdbc.queryForList(
                "SELECT event_type || ':' || held_by FROM cycle_lease_log ORDER BY lease_log_id",
                String.class);
    }

    private static FciException refusal(Runnable call) {
        try {
            call.run();
        } catch (FciException e) {
            return e;
        }
        throw new AssertionError("not refused");
    }

    @Test
    void SRS_15_28_oneHolderPerInstanceAndTheRefusalNamesItAndSinceWhen() {
        assertThat(leases.current(CYCLE)).isEmpty();
        leases.requireFree(CYCLE);
        leases.acquire(CYCLE, CycleLeases.Action.FREEZE, "maker.a", null);

        CycleLeases.Lease held = leases.current(CYCLE).orElseThrow();
        assertThat(held.action()).isEqualTo("FREEZE");
        assertThat(held.heldBy()).isEqualTo("maker.a");
        assertThat(held.acquiredAt()).isEqualTo(T0);
        assertThat(held.runId()).isNull();
        assertThat(held.expired()).isFalse();

        FciException e = refusal(() -> leases.requireFree(CYCLE));
        assertThat(e.getErrorCode()).isEqualTo(ApiErrorCode.CYCLE_LEASE_HELD);
        // 06:30 UTC is 12:00 in India.
        assertThat(e.getMessageArgs()).containsExactly("FREEZE", "maker.a", "2026-10-25 12:00 IST");
        assertThat(
                        refusal(
                                        () ->
                                                leases.acquire(
                                                        CYCLE,
                                                        CycleLeases.Action.LOCK,
                                                        "checker.b",
                                                        null))
                                .getErrorCode())
                .isEqualTo(ApiErrorCode.CYCLE_LEASE_HELD);
        // Another instance is never blocked.
        leases.acquire(CYCLE + 1, CycleLeases.Action.LOCK, "checker.b", null);
        assertThat(events()).containsExactly("ACQUIRED:maker.a", "ACQUIRED:checker.b");
    }

    @Test
    void BR_CYC_015_aBeatingLeaseHoldsAndAStoppedOneIsTakenOverAndLoggedExpired() {
        leases.acquire(CYCLE, CycleLeases.Action.COMPUTE, "run.owner", null);
        now.set(T0.plus(Duration.ofMinutes(4)));
        leases.heartbeat(CYCLE, "run.owner");
        leases.heartbeat(CYCLE, "someone.else");
        now.set(T0.plus(Duration.ofMinutes(8)));
        assertThat(leases.current(CYCLE).orElseThrow().expired()).isFalse();
        assertThat(refusal(() -> leases.requireFree(CYCLE)).getErrorCode())
                .isEqualTo(ApiErrorCode.CYCLE_LEASE_HELD);

        // Five minutes without a beat: expired, no longer holding, taken over.
        now.set(T0.plus(Duration.ofMinutes(10)));
        assertThat(leases.current(CYCLE).orElseThrow().expired()).isTrue();
        leases.requireFree(CYCLE);
        leases.acquire(CYCLE, CycleLeases.Action.FREEZE, "maker.a", null);
        assertThat(leases.current(CYCLE).orElseThrow().heldBy()).isEqualTo("maker.a");
        assertThat(events())
                .containsExactly("ACQUIRED:run.owner", "EXPIRED:run.owner", "ACQUIRED:maker.a");
    }

    @Test
    void BR_CYC_015_twoAcquirersRacingTheKeyDecidesAndTheLoserIsRefusedNamingTheWinner() {
        race.set(
                () ->
                        jdbc.update(
                                "INSERT INTO cycle_lease VALUES (?, 'COMPUTE', 'winner', ?, ?,"
                                        + " NULL)",
                                CYCLE,
                                java.sql.Timestamp.from(T0),
                                java.sql.Timestamp.from(T0)));
        FciException e =
                refusal(() -> leases.acquire(CYCLE, CycleLeases.Action.FREEZE, "loser", null));
        assertThat(e.getMessageArgs()[1]).isEqualTo("winner");
        assertThat(events()).isEmpty();

        // The winner was gone again before the loser read it: the key error itself surfaces.
        jdbc.update("DELETE FROM cycle_lease");
        race.set(
                () -> {
                    throw new DuplicateKeyException("pk_cycle_lease");
                });
        assertThatThrownBy(() -> leases.acquire(CYCLE, CycleLeases.Action.FREEZE, "loser", null))
                .isInstanceOf(DuplicateKeyException.class);
    }

    @Test
    void SRS_15_28_aRunKeepsItsOwnLeaseOnRestartBeatsItAndReleasesOnlyItsOwn() {
        leases.acquireForRun(CYCLE, "maker.a", 7L);
        now.set(T0.plus(Duration.ofMinutes(3)));
        // The restart of run 7 keeps the lease (no second acquisition) and renews it.
        leases.acquireForRun(CYCLE, "maker.a", 7L);
        assertThat(leases.current(CYCLE).orElseThrow().heartbeatAt())
                .isEqualTo(T0.plus(Duration.ofMinutes(3)));
        now.set(T0.plus(Duration.ofMinutes(6)));
        leases.heartbeatRun(7L);
        leases.heartbeatRun(8L);
        assertThat(leases.current(CYCLE).orElseThrow().runId()).isEqualTo(7L);
        // Another run is refused while run 7 holds it; it does not release run 7's lease.
        assertThat(refusal(() -> leases.acquireForRun(CYCLE, "maker.b", 8L)).getErrorCode())
                .isEqualTo(ApiErrorCode.CYCLE_LEASE_HELD);
        leases.releaseRun(CYCLE, 8L);
        assertThat(leases.current(CYCLE)).isPresent();
        // A holder who is not the run's does not release it either; the run does.
        leases.release(CYCLE, "maker.b");
        assertThat(leases.current(CYCLE)).isPresent();
        leases.releaseRun(CYCLE, 7L);
        assertThat(leases.current(CYCLE)).isEmpty();
        leases.releaseRun(CYCLE, 7L);
        assertThat(events()).containsExactly("ACQUIRED:maker.a", "RELEASED:maker.a");
    }

    @Test
    void SRS_15_28_forceReleaseTakesOnlyTheLeaseTheRequestNamedAndLogsWhoWhyAndTheOtp() {
        leases.acquire(CYCLE, CycleLeases.Action.COMPUTE, "run.owner", null);
        assertThat(
                        leases.forceRelease(
                                CYCLE,
                                "run.owner",
                                T0.minusSeconds(1),
                                "checker.b",
                                "stuck",
                                90L,
                                5L))
                .isFalse();
        assertThat(leases.forceRelease(CYCLE, "other", T0, "checker.b", "stuck", 90L, 5L))
                .isFalse();
        assertThat(leases.current(CYCLE)).isPresent();

        assertThat(leases.forceRelease(CYCLE, "run.owner", T0, "checker.b", "stuck", 90L, 5L))
                .isTrue();
        assertThat(leases.current(CYCLE)).isEmpty();
        Map<String, Object> log =
                jdbc.queryForMap(
                        "SELECT lease_action, released_by, force_release_reason, approval_id,"
                                + " otp_challenge_id FROM cycle_lease_log WHERE event_type ="
                                + " 'FORCE_RELEASED'");
        assertThat(log)
                .containsEntry("LEASE_ACTION", "COMPUTE")
                .containsEntry("RELEASED_BY", "checker.b")
                .containsEntry("FORCE_RELEASE_REASON", "stuck")
                .containsEntry("APPROVAL_ID", 90L)
                .containsEntry("OTP_CHALLENGE_ID", 5L);
        // Nothing held any more: a second release finds nothing.
        assertThat(leases.forceRelease(CYCLE, "run.owner", T0, "checker.b", "stuck", 91L, 6L))
                .isFalse();
    }
}
