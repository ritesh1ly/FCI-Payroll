package in.gov.fci.payroll.payroll.orchestration;

import static org.assertj.core.api.Assertions.assertThat;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.verifyNoInteractions;

import in.gov.fci.payroll.audit.api.AuditService;
import in.gov.fci.payroll.platform.approval.ApprovalDecided;
import in.gov.fci.payroll.platform.approval.ApprovalStatus;
import java.math.BigDecimal;
import java.time.Instant;
import java.util.List;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import tools.jackson.databind.json.JsonMapper;

/**
 * SRS-15-19, SRS-G-1, SRS-G-33, SRS-G-37 (plan 05 phase 05g): every I-19 decision on an in-memory
 * copy of {@code mdp_transaction}: approval, rejection (final before approval, no change after),
 * return (no change), cancellation, and an amendment that never edits an approved entry in place.
 */
class DirectPayrollEffectTest {

    private final AuditService audit = mock(AuditService.class);
    private JdbcTemplate jdbc;
    private DirectPayrollEffect effect;

    @BeforeEach
    void schema() {
        org.h2.jdbcx.JdbcDataSource h2 = new org.h2.jdbcx.JdbcDataSource();
        h2.setURL("jdbc:h2:mem:mdpeffect;MODE=Oracle;DB_CLOSE_DELAY=-1");
        jdbc = new JdbcTemplate(h2);
        jdbc.execute("DROP TABLE IF EXISTS mdp_transaction");
        jdbc.execute("DROP TABLE IF EXISTS approval_queue");
        jdbc.execute(
                "CREATE TABLE mdp_transaction (mdp_id BIGINT GENERATED BY DEFAULT AS IDENTITY"
                    + " PRIMARY KEY, cycle_instance_id BIGINT, employee_id BIGINT, component_id"
                    + " BIGINT, amount NUMBER(12,2), mdp_status VARCHAR(15), reason VARCHAR(500),"
                    + " approval_id BIGINT, entered_by VARCHAR(50))");
        jdbc.execute("CREATE TABLE approval_queue (approval_id BIGINT, submitted_by VARCHAR(50))");
        jdbc.update("INSERT INTO approval_queue VALUES (70, 'maker.delhi')");
        effect = new DirectPayrollEffect(jdbc, audit, JsonMapper.builder().build());
    }

    private long entry(String status) {
        jdbc.update(
                "INSERT INTO mdp_transaction (cycle_instance_id, employee_id, component_id, amount,"
                        + " mdp_status, reason, entered_by) VALUES (1, 2, 3, 25.00, ?, 'LWF',"
                        + " 'maker.delhi')",
                status);
        return jdbc.queryForObject("SELECT MAX(mdp_id) FROM mdp_transaction", Long.class);
    }

    private String status(long id) {
        return jdbc.queryForObject(
                "SELECT mdp_status FROM mdp_transaction WHERE mdp_id = ?", String.class, id);
    }

    private static ApprovalDecided decided(
            String entity, ApprovalStatus outcome, long id, String op, String amount) {
        return new ApprovalDecided(
                70L,
                "I-19",
                entity,
                String.valueOf(id),
                outcome,
                "",
                "{\"mdpId\":"
                        + id
                        + ",\"op\":\""
                        + op
                        + "\",\"reason\":\"checked\""
                        + (amount == null ? "" : ",\"amount\":\"" + amount + "\"")
                        + "}",
                "ddo.delhi",
                Instant.parse("2026-10-26T06:00:00Z"));
    }

    @Test
    void SRS_15_19_anotherEntityOrAReturnChangesNothing() {
        long id = entry("ENTERED");
        effect.on(decided("payroll_cycle_instance", ApprovalStatus.APPROVED, id, "CREATE", null));
        effect.on(
                decided(DirectPayrollService.ENTITY, ApprovalStatus.RETURNED, id, "CREATE", null));
        assertThat(status(id)).isEqualTo("ENTERED");
        verifyNoInteractions(audit);
    }

    @Test
    void SRS_G_33_aRejectionIsFinalBeforeApprovalAndChangesNothingAfterIt() {
        long entered = entry("ENTERED");
        effect.on(
                decided(
                        DirectPayrollService.ENTITY,
                        ApprovalStatus.REJECTED,
                        entered,
                        "CREATE",
                        null));
        assertThat(status(entered)).isEqualTo("CANCELLED");
        long approved = entry("APPROVED");
        effect.on(
                decided(
                        DirectPayrollService.ENTITY,
                        ApprovalStatus.REJECTED,
                        approved,
                        "CANCEL",
                        null));
        assertThat(status(approved)).isEqualTo("APPROVED");
    }

    @Test
    void SRS_15_19_anApprovalOfACaptureOrACorrectedEntryApprovesIt() {
        long captured = entry("ENTERED");
        effect.on(
                decided(
                        DirectPayrollService.ENTITY,
                        ApprovalStatus.APPROVED,
                        captured,
                        "CREATE",
                        null));
        assertThat(status(captured)).isEqualTo("APPROVED");
        long corrected = entry("AMENDED");
        effect.on(
                decided(
                        DirectPayrollService.ENTITY,
                        ApprovalStatus.APPROVED,
                        corrected,
                        "AMEND",
                        "30.00"));
        assertThat(status(corrected)).isEqualTo("APPROVED");
    }

    @Test
    void SRS_G_37_anApprovedEntryIsCancelledOrReplacedNeverEditedInPlace() {
        long cancelled = entry("APPROVED");
        effect.on(
                decided(
                        DirectPayrollService.ENTITY,
                        ApprovalStatus.APPROVED,
                        cancelled,
                        "CANCEL",
                        null));
        assertThat(status(cancelled)).isEqualTo("CANCELLED");

        long amended = entry("APPROVED");
        effect.on(
                decided(
                        DirectPayrollService.ENTITY,
                        ApprovalStatus.APPROVED,
                        amended,
                        "AMEND",
                        "40.50"));
        assertThat(status(amended)).isEqualTo("CANCELLED");
        List<java.util.Map<String, Object>> replacement =
                jdbc.queryForList(
                        "SELECT amount, mdp_status, entered_by, reason FROM mdp_transaction WHERE"
                                + " mdp_id > ?",
                        amended);
        assertThat(replacement).hasSize(1);
        assertThat((BigDecimal) replacement.get(0).get("AMOUNT")).isEqualByComparingTo("40.50");
        assertThat(replacement.get(0))
                .containsEntry("MDP_STATUS", "APPROVED")
                .containsEntry("ENTERED_BY", "maker.delhi");
        assertThat((String) replacement.get(0).get("REASON")).startsWith("Amends MDP " + amended);
    }
}
