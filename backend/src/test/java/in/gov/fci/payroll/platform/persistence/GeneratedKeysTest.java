package in.gov.fci.payroll.platform.persistence;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import java.util.List;
import java.util.Map;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.core.SqlProvider;
import org.springframework.jdbc.support.GeneratedKeyHolder;

class GeneratedKeysTest {

    @Test
    void returnsTheGeneratedIdAndFailsClearlyWithoutOne() {
        assertThat(GeneratedKeys.id(new GeneratedKeyHolder(List.of(Map.of("id", 42L)))))
                .isEqualTo(42L);
        assertThatThrownBy(() -> GeneratedKeys.id(new GeneratedKeyHolder()))
                .isInstanceOf(IllegalStateException.class)
                .hasMessageContaining("no generated key");
    }

    /**
     * Oracle review F2: the key of the row this INSERT wrote, even when another row of the same
     * natural key already holds a higher id (which MAX(id) would have answered).
     */
    @Test
    void anInsertAnswersTheKeyOfItsOwnRowNotTheHighestIdOfItsKind() {
        org.h2.jdbcx.JdbcDataSource h2 = new org.h2.jdbcx.JdbcDataSource();
        h2.setURL("jdbc:h2:mem:generatedkeys;MODE=Oracle;DB_CLOSE_DELAY=-1");
        JdbcTemplate jdbc = new JdbcTemplate(h2);
        jdbc.execute("DROP TABLE IF EXISTS event");
        jdbc.execute(
                "CREATE TABLE event (event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                        + " source_key VARCHAR(20), note VARCHAR(20))");
        // Another session's row of the same source, with a higher id (a cached identity block).
        jdbc.update("INSERT INTO event (event_id, source_key) VALUES (900, 'K-1')");
        long mine =
                GeneratedKeys.insert(
                        jdbc,
                        "INSERT INTO event (source_key, note) VALUES (?, ?)",
                        "event_id",
                        "K-1",
                        null);
        assertThat(mine).isNotEqualTo(900L);
        assertThat(
                        jdbc.queryForObject(
                                "SELECT source_key FROM event WHERE event_id = ?",
                                String.class,
                                mine))
                .isEqualTo("K-1");
        assertThat(
                        GeneratedKeys.insert(
                                jdbc,
                                "INSERT INTO event (source_key) VALUES ('K-2')",
                                "event_id",
                                (Object[]) null))
                .isGreaterThan(mine);
        // A value the statement has no placeholder for: the statement is closed, the error raised.
        assertThatThrownBy(
                        () ->
                                GeneratedKeys.insert(
                                        jdbc,
                                        "INSERT INTO event (source_key) VALUES (?)",
                                        "event_id",
                                        "K-3",
                                        "extra"))
                .isInstanceOf(org.springframework.dao.DataAccessException.class);
        GeneratedKeys.Insert sent = new GeneratedKeys.Insert("INSERT", "id", null);
        assertThat(sent.args()).isNull();
        assertThat(((SqlProvider) sent).getSql()).isEqualTo("INSERT");
        assertThat(new GeneratedKeys.Insert("INSERT", "id", new Object[] {1}).args())
                .containsExactly(1);
    }
}
