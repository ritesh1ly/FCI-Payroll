    // SRS-NF-5 / NF-7: a PDF the batch has not stored yet defers; a recorded generation failure
    // fails the e-mail with its reason; neither blocks the others.
    @Test
    void SRS_17_12_aPdfNotGeneratedYetDefersAndAGenerationFailureFailsTheEmail() {
        queued(3, "GEN");
        List<MemberDocuments> stored =
                List.of(
                        new MemberDocuments() {
                            @Override
                            public String documentType() {
                                return "PAYSLIP";
                            }

                            @Override
                            public Optional<Rendered> render(long e, String p, String source) {
                                return switch (source) {
                                    case "GEN1" -> throw new DocumentNotReadyException("not yet");
                                    case "GEN2" ->
                                            throw new DocumentFailedException(
                                                    "Payslip generation failed: no bank advice");
                                    default ->
                                            Optional.of(
                                                    new Rendered(
                                                            MailAttachment.pdf("g.pdf", PDF),
                                                            Map.of()));
                                };
                            }
                        });
        Server server = new Server();
        Instant at = minute(110);
        dispatch(server, true, false, "", 1, stored).run(at);
        Map<String, String> byKey = new java.util.HashMap<>();
        jdbc.query(
                "SELECT d.source_key, n.delivery_status, d.attempt_count, n.delivery_detail FROM"
                        + " document_mail d JOIN notification n ON n.notification_id ="
                        + " d.notification_id AND n.created_at = d.notification_created_at WHERE"
                        + " d.period_key = 'GEN'",
                (java.sql.ResultSet rs) -> {
                    byKey.put(
                            rs.getString(1),
                            rs.getString(2) + "|" + rs.getInt(3) + "|" + rs.getString(4));
                });
        assertThat(byKey.get("GEN1")).isEqualTo("QUEUED|0|Document not generated yet");
        assertThat(byKey.get("GEN2"))
                .startsWith("FAILED|1|Document generation failed:")
                .contains("no bank advice");
        assertThat(byKey.get("GEN3")).startsWith("SENT|1|");
    }
