    // Rejected credentials: the channel pauses, alerted on X-03, no e-mail spends an attempt.
    @Test
    void SRS_INT_6_rejectedCredentialsPauseTheChannelWithoutSpendingAnyAttempt() throws Exception {
        queued(5, "AUTH");
        Server server = new Server();
        server.failure = new MailAuthenticationException("535 5.7.8 Authentication failed");
        Instant at = minute(70);
        assertThat(dispatch(server, true, false, "", 1, tiny()).run(at)).isZero();
        assertThat(
                        jdbc.queryForObject(
                                "SELECT MAX(attempt_count) FROM document_mail WHERE period_key ="
                                        + " 'AUTH'",
                                Integer.class))
                .isZero();
        assertThat(channel.pausedUntil(at)).isPresent();
        assertThat(
                        jdbc.queryForObject(
                                "SELECT COUNT(*) FROM audit_event WHERE entity_name ="
                                        + " 'mail_channel_state'",
                                Long.class))
                .isPositive();
        server.failure = null;
        assertThat(dispatch(server, true, false, "", 1, tiny()).run(at.plusSeconds(60)))
                .as("still paused")
                .isZero();
        jdbc.update("UPDATE mail_channel_state SET paused_until = ?", Timestamp.from(at));
        assertThat(dispatch(server, true, false, "", 1, tiny()).run(at.plusSeconds(120)))
                .isEqualTo(5);
        Session admin = login("sysadmin@fci-demo.test", "SYSTEM_ADMINISTRATOR", "HQ001");
        JsonNode view = body(mvc.perform(userGet(admin, "/v1/document-mails/channel")).andReturn());
        assertThat(view.path("configured").asBoolean()).isTrue();
        assertThat(view.path("byStatus").path("SENT").asLong()).isPositive();
        assertThat(view.toString()).as("counts only").doesNotContain("@fci-demo");
        Session hr = login("hr.delhi@fci-demo.test", "ESTABLISHMENT_HR", "DH001");
        assertThat(
                        mvc.perform(userGet(hr, "/v1/document-mails/channel"))
                                .andReturn()
                                .getResponse()
                                .getStatus())
                .isEqualTo(403);
    }

    // SRS-INT-6: an outage opens the breaker; sending pauses, then resumes at the probe.
    @Test
    void SRS_INT_6_anOutageOpensTheBreakerAndSendingResumesAfterTheProbe() {
        queued(8, "DOWN");
        Server server = new Server();
        server.failure = new MailSendException("421 4.3.2 Service not available");
        Instant at = minute(80);
        dispatch(server, true, false, "", 1, tiny()).run(at);
        long tried =
                jdbc.queryForObject(
                        "SELECT COUNT(*) FROM document_mail WHERE period_key = 'DOWN' AND"
                                + " attempt_count > 0",
                        Long.class);
        assertThat(tried).as("the breaker (threshold 5) stopped the run").isEqualTo(5);
        assertThat(status("DOWN", "FAILED")).as("4xx is transient").isZero();
        server.failure = null;
        assertThat(dispatch(server, true, false, "", 1, tiny()).run(at.plusSeconds(3600)))
                .as("open: nothing goes before the probe time")
                .isZero();
        jdbc.update(
                "UPDATE interface_breaker_state SET next_probe_at = TIMESTAMP '2000-01-01"
                        + " 00:00:00' WHERE interface_id = (SELECT interface_id FROM"
                        + " interface_registry WHERE interface_code = 'MEMBER_EMAIL')");
        dispatch(server, true, false, "", 1, tiny()).run(at.plusSeconds(86_400));
        assertThat(status("DOWN", "SENT")).isEqualTo(8);
        assertThat(
                        jdbc.queryForObject(
                                "SELECT breaker_state FROM interface_breaker_state WHERE"
                                        + " interface_id = (SELECT interface_id FROM"
                                        + " interface_registry WHERE interface_code ="
                                        + " 'MEMBER_EMAIL')",
                                String.class))
                .isEqualTo("CLOSED");
    }

    // SRS l.3763: the address at sending is used; an unusable address fails, never sent.
    @Test
    void SRS_17_1_theCurrentAddressIsUsedAndAnInvalidOneIsFailed() {
        YearMonth jan = YearMonth.of(1997, 1);
        lock(lockedMonth(jan), jan);
        jdbc.update(
                "UPDATE employee SET email_address = 'rakesh.new@fci-demo.test' WHERE employee_id"
                        + " = ?",
                self);
        Server server = new Server();
        dispatch(server).run(minute(90));
        assertThat(server.about("199701").getFirst().email()).isEqualTo("rakesh.new@fci-demo.test");
        for (String[] bad :
                new String[][] {
                    {"1997-02", "rakesh sharma@fci-demo.test"},
                    {"1997-03", "rakesh@नम.in"},
                    {"1997-04", "a".repeat(70) + "@fci-demo.test"},
                    {"1997-05", "rakesh@localhost"}
                }) {
            YearMonth m = YearMonth.parse(bad[0]);
            lock(lockedMonth(m), m);
            jdbc.update(
                    "UPDATE employee SET email_address = ? WHERE employee_id = ?", bad[1], self);
            dispatch(server).run(minute(91));
            Map<String, Object> r = row(self, "PAYSLIP", bad[0].replace("-", ""));
            assertThat(r)
                    .as(bad[1])
                    .containsEntry("DELIVERY_STATUS", "FAILED")
                    .containsEntry("FAILURE_CLASS", "ADDRESS")
                    .containsEntry("DELIVERY_DETAIL", "Invalid e-mail address");
        }
        assertThat(server.sent).hasSize(1);
    }

    // A held payment: no payslip e-mail while held; sent once the hold ends (attempt not spent).
    @Test
    void SRS_17_1_aHeldPaymentIsMailedOnceTheHoldEnds() {
        YearMonth month = YearMonth.of(1997, 6);
        long cycle = lockedMonth(month);
        jdbc.update(
                "INSERT INTO payroll_exception (cycle_instance_id, employee_id, exception_code,"
                        + " severity, detail) VALUES (?, ?, 'PAYMENT_HELD', 'WARNING', 'it hold')",
                cycle,
                self);
        lock(cycle, month);
        assertThat((String) row(self, "PAYSLIP", "199706").get("DELIVERY_DETAIL"))
                .startsWith("Payment held");
        Server server = new Server();
        Instant at = minute(100);
        dispatch(server).run(at);
        Map<String, Object> held = row(self, "PAYSLIP", "199706");
        assertThat(held).containsEntry("DELIVERY_STATUS", "QUEUED");
        assertThat(((Number) held.get("ATTEMPT_COUNT")).intValue()).isZero();
        assertThat(server.about("199706")).isEmpty();
        jdbc.update(
                "UPDATE payroll_exception SET exception_status = 'RESOLVED', resolved_at ="
                        + " CURRENT_TIMESTAMP WHERE cycle_instance_id = ? AND employee_id = ?",
                cycle,
                self);
        dispatch(server).run(at.plusSeconds(3600));
        assertThat(server.about("199706")).as("before the re-check").isEmpty();
        dispatch(server).run(at.plusSeconds(25 * 3600));
        assertThat(server.about("199706")).hasSize(1);
    }

