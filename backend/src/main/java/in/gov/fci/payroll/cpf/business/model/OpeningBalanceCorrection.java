package in.gov.fci.payroll.cpf.business.model;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.math.BigDecimal;
import java.time.Instant;
import java.time.LocalDate;

/**
 * {@code opening_balance_correction}: one part (employee, employer or VPF) of an I-22 PF / CPF
 * opening-balance correction (target DDL v4.0 Section 3; SRS-6-43, SRS-6-44, BR-CPF-025 … 027). The
 * parts of one request share {@code correction_ref}; the old amount is kept beside the new one, so
 * the original opening balance is never overwritten. Three tiers, three different users, an OTP at
 * each approval tier ({@code chk_ob_corr_users}, {@code chk_ob_corr_tier2}, {@code
 * chk_ob_corr_tier3}).
 */
@Entity
@Table(name = "opening_balance_correction")
public class OpeningBalanceCorrection {

    /** {@code correction_status} (DDL CHECK). */
    public enum Status {
        DRAFT,
        PENDING_AGM_CPF,
        PENDING_HQ_CPF,
        RETURNED,
        APPROVED,
        REJECTED,
        BLOCKED_CPF_DIVISION,
        APPLIED,
        CANCELLED
    }

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "correction_id")
    private Long correctionId;

    @Column(name = "correction_ref", nullable = false, length = 20)
    private String correctionRef;

    @Column(name = "employee_id", nullable = false)
    private Long employeeId;

    @Column(name = "balance_domain", nullable = false, length = 20)
    private String balanceDomain;

    @Column(name = "fin_year", nullable = false, length = 9)
    private String finYear;

    @Column(name = "as_at_date", nullable = false)
    private LocalDate asAtDate;

    @Column(name = "balance_component", nullable = false, length = 30)
    private String balanceComponent;

    @Column(name = "old_amount", nullable = false, precision = 14, scale = 2)
    private BigDecimal oldAmount;

    @Column(name = "new_amount", nullable = false, precision = 14, scale = 2)
    private BigDecimal newAmount;

    // Generated by the database (new_amount - old_amount): read, never written.
    @Column(
            name = "difference_amount",
            precision = 14,
            scale = 2,
            insertable = false,
            updatable = false)
    private BigDecimal differenceAmount;

    @Column(name = "reason_code", nullable = false, length = 40)
    private String reasonCode;

    @Column(name = "reason", nullable = false, length = 1000)
    private String reason;

    @Column(name = "interest_effective_date", nullable = false)
    private LocalDate interestEffectiveDate;

    @Column(name = "interest_effect_amount", precision = 14, scale = 2)
    private BigDecimal interestEffectAmount;

    @Column(name = "evidence_attachment_id")
    private Long evidenceAttachmentId;

    @Column(name = "correction_status", nullable = false, length = 25)
    private String correctionStatus;

    @Column(name = "status_reason", length = 500)
    private String statusReason;

    @Column(name = "checker_user", length = 50)
    private String checkerUser;

    @Column(name = "checker_at")
    private Instant checkerAt;

    @Column(name = "otp_challenge_id")
    private Long otpChallengeId;

    @Column(name = "hq_approver_user", length = 50)
    private String hqApproverUser;

    @Column(name = "hq_approved_at")
    private Instant hqApprovedAt;

    @Column(name = "hq_otp_challenge_id")
    private Long hqOtpChallengeId;

    @Column(name = "approval_id")
    private Long approvalId;

    @Column(name = "applied_at")
    private Instant appliedAt;

    @Column(name = "ssp_sync_queued_at")
    private Instant sspSyncQueuedAt;

    @Column(name = "raised_by", nullable = false, length = 50)
    private String raisedBy;

    @Column(name = "raised_at", nullable = false)
    private Instant raisedAt;

    protected OpeningBalanceCorrection() {}

    /** One changed part of a correction as the Manager (CPF) raises it. */
    public static OpeningBalanceCorrection raise(
            String ref,
            Long employeeId,
            String finYear,
            LocalDate asAtDate,
            String component,
            BigDecimal oldAmount,
            BigDecimal newAmount,
            String reasonCode,
            String reason,
            LocalDate interestEffectiveDate,
            Long evidenceAttachmentId,
            Status status,
            String statusReason,
            String raisedBy,
            Instant now) {
        OpeningBalanceCorrection c = new OpeningBalanceCorrection();
        c.correctionRef = ref;
        c.employeeId = employeeId;
        c.balanceDomain = "CPF";
        c.finYear = finYear;
        c.asAtDate = asAtDate;
        c.balanceComponent = component;
        c.oldAmount = oldAmount;
        c.newAmount = newAmount;
        c.reasonCode = reasonCode;
        c.reason = reason;
        c.interestEffectiveDate = interestEffectiveDate;
        c.evidenceAttachmentId = evidenceAttachmentId;
        c.correctionStatus = status.name();
        c.statusReason = statusReason;
        c.raisedBy = raisedBy;
        c.raisedAt = now;
        return c;
    }

    /** The reference of the request, set once its first part has its id. */
    public void reference(String ref) {
        correctionRef = ref;
    }

    /** The evidence attached through the order-copy control. */
    public void evidence(Long attachmentId) {
        evidenceAttachmentId = attachmentId;
    }

    public void submitted(Long approval) {
        approvalId = approval;
    }

    /** Tier 2: the AGM (CPF) approved with OTP; on to the Headquarters CPF approver. */
    public void checked(String checker, Long otp, Instant at) {
        checkerUser = checker;
        otpChallengeId = otp;
        checkerAt = at;
        correctionStatus = Status.PENDING_HQ_CPF.name();
    }

    /** Tier 3: the Headquarters CPF approver approved with OTP. */
    public void approved(String approver, Long otp, Instant at) {
        hqApproverUser = approver;
        hqOtpChallengeId = otp;
        hqApprovedAt = at;
        correctionStatus = Status.APPROVED.name();
    }

    /** Returned or rejected at a tier: nothing applies; the reason is recorded. */
    public void closed(Status status, String reason) {
        correctionStatus = status.name();
        statusReason = reason;
    }

    /** SRS-6-44: written to the ledger, with the interest effect (null when not computable). */
    public void applied(BigDecimal interestEffect, Instant at) {
        interestEffectAmount = interestEffect;
        appliedAt = at;
        correctionStatus = Status.APPLIED.name();
    }

    public Long getCorrectionId() {
        return correctionId;
    }

    public String getCorrectionRef() {
        return correctionRef;
    }

    public Long getEmployeeId() {
        return employeeId;
    }

    public String getBalanceDomain() {
        return balanceDomain;
    }

    public String getFinYear() {
        return finYear;
    }

    public LocalDate getAsAtDate() {
        return asAtDate;
    }

    public String getBalanceComponent() {
        return balanceComponent;
    }

    public BigDecimal getOldAmount() {
        return oldAmount;
    }

    public BigDecimal getNewAmount() {
        return newAmount;
    }

    public BigDecimal getDifferenceAmount() {
        return differenceAmount;
    }

    public String getReasonCode() {
        return reasonCode;
    }

    public String getReason() {
        return reason;
    }

    public LocalDate getInterestEffectiveDate() {
        return interestEffectiveDate;
    }

    public BigDecimal getInterestEffectAmount() {
        return interestEffectAmount;
    }

    public Long getEvidenceAttachmentId() {
        return evidenceAttachmentId;
    }

    public String getCorrectionStatus() {
        return correctionStatus;
    }

    public String getStatusReason() {
        return statusReason;
    }

    public String getCheckerUser() {
        return checkerUser;
    }

    public Instant getCheckerAt() {
        return checkerAt;
    }

    public Long getOtpChallengeId() {
        return otpChallengeId;
    }

    public String getHqApproverUser() {
        return hqApproverUser;
    }

    public Instant getHqApprovedAt() {
        return hqApprovedAt;
    }

    public Long getHqOtpChallengeId() {
        return hqOtpChallengeId;
    }

    public Long getApprovalId() {
        return approvalId;
    }

    public Instant getAppliedAt() {
        return appliedAt;
    }

    public Instant getSspSyncQueuedAt() {
        return sspSyncQueuedAt;
    }

    public String getRaisedBy() {
        return raisedBy;
    }

    public Instant getRaisedAt() {
        return raisedAt;
    }
}
