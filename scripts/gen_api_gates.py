#!/usr/bin/env python3
"""OD-130: writes frontend/src/shared/api/apiGates.ts from the controllers' static gates.

The browser client refuses locally a call the session's permissions cannot pass, so a screen drawn
for a role never sends the server a call that would log the user out as an offence. Only the three
static gate forms are read (@authz.gate, @authz.gateEither, @authz.can), the same forms
GateFirstInterceptor reads; any other expression, or a route not found here, is simply not checked
locally and the server decides as always.

    python scripts/gen_api_gates.py          write the file
    python scripts/gen_api_gates.py --check  exit 1 when the file is out of date
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCES = ROOT / "backend/src/main/java/in/gov/fci/payroll"
TARGET = ROOT / "frontend/src/shared/api/apiGates.ts"

CLASS_MAPPING = re.compile(r'^@RequestMapping\(\s*(?:path\s*=\s*|value\s*=\s*)?"([^"]*)"', re.M)
CLASS_GATE = re.compile(r'^@PreAuthorize\(\s*((?:"[^"]*"\s*\+?\s*)+)\)', re.M)
METHOD_MAPPING = re.compile(
    r"@(Get|Post|Put|Patch)Mapping(?:\(\s*(?:path\s*=\s*|value\s*=\s*)?(\{[^}]*\}|\"[^\"]*\")?[^)]*\))?"
)
METHOD_GATE = re.compile(r'@PreAuthorize\(\s*((?:"[^"]*"\s*\+?\s*)+)\)')
PART = r"\s*'([A-Z]-\d{2})'\s*,\s*'([A-Z_]+)'\s*"
GATE = re.compile(rf"^@authz\.(?:gate|can)\({PART}\)$")
EITHER = re.compile(rf"^@authz\.gateEither\({PART},{PART}\)$")


def expression(raw):
    return "".join(re.findall(r'"([^"]*)"', raw)).strip()


def permissions(expr):
    m = GATE.match(expr)
    if m:
        return [f"{m.group(1)}:{m.group(2)}"]
    m = EITHER.match(expr)
    if m:
        return [f"{m.group(1)}:{m.group(2)}", f"{m.group(3)}:{m.group(4)}"]
    return None


def paths_of(raw):
    if raw is None:
        return [""]
    return re.findall(r'"([^"]*)"', raw) or [""]


def entries():
    rows = set()
    for source in sorted(SOURCES.rglob("*Controller.java")):
        text = source.read_text(encoding="utf-8")
        mapped = CLASS_MAPPING.search(text)
        prefix = mapped.group(1) if mapped else ""
        class_gate = CLASS_GATE.search(text)
        for m in METHOD_MAPPING.finditer(text):
            signature = text[m.end() : m.end() + 600].split(" public ")[0]
            gate = METHOD_GATE.search(signature) or METHOD_GATE.search(
                text[max(0, m.start() - 300) : m.start()].rsplit("\n\n", 1)[-1]
            )
            raw = gate.group(1) if gate else class_gate.group(1) if class_gate else None
            held = permissions(expression(raw)) if raw else None
            if not held:
                continue
            for tail in paths_of(m.group(2)):
                path = re.sub(r"\{[^}]*\}", "{}", prefix + tail).rstrip("/")
                rows.add((m.group(1).upper(), path, tuple(held)))
    return sorted(rows)


def render(rows):
    lines = [
        "// GENERATED by scripts/gen_api_gates.py from the controllers: do not edit (OD-130).",
        "// [method, route ({} = a path value), permissions: any one of them passes the gate]",
        "export const API_GATES: readonly (readonly [string, string, readonly string[]])[] = [",
    ]
    for method, path, held in rows:
        joined = ", ".join(f"'{p}'" for p in held)
        lines.append(f"  ['{method}', '{path}', [{joined}]],")
    lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    content = render(entries())
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != content:
            print("frontend/src/shared/api/apiGates.ts is out of date: python scripts/gen_api_gates.py")
            return 1
        return 0
    TARGET.write_text(content, encoding="utf-8", newline="\n")
    print(f"{content.count(chr(10)) - 4} gates written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
