#!/usr/bin/env python3
"""Rebuilds the status of the second user-story gap list (US-GAP-100..362) in docs/tracker/PENDING.md.

Reads the Outcome column of docs/quality/user-stories/GAP_ANALYSIS_2.md (section 3) and writes, between the markers
<!-- GAP2-STATUS:BEGIN --> and <!-- GAP2-STATUS:END --> in PENDING.md, a table per module (done / partial / waiting
FCI / blocked / story fixed / dropped / open) and the open gap IDs of each module. Run after every batch:

    python scripts/quality/gap2_status.py            # rewrite the section
    python scripts/quality/gap2_status.py --check    # exit 1 if the section is out of date
"""
import datetime
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
GAPS = ROOT / "docs/quality/user-stories/GAP_ANALYSIS_2.md"
PENDING = ROOT / "docs/tracker/PENDING.md"
BEGIN, END = "<!-- GAP2-STATUS:BEGIN -->", "<!-- GAP2-STATUS:END -->"
KINDS = ["done", "partial", "fci", "blocked", "story", "dropped", "open"]


def classify(outcome: str) -> str:
    u = outcome.upper()
    if not outcome:
        return "open"
    if u.startswith("BLOCKED"):
        return "blocked"
    if u.startswith("PARTIAL"):
        return "partial"
    if u.startswith("WAITING FCI"):
        return "fci"
    if u.startswith("STORY FIXED"):
        return "story"
    if u.startswith("DROPPED"):
        return "dropped"
    return "done"


def table() -> str:
    text = GAPS.read_text(encoding="utf8")
    sec3 = text.split("## 3. All findings, by module")[1].split("\n## 4.")[0]
    rows_out, totals, open_lines = [], dict.fromkeys(KINDS, 0), []
    total_gaps = 0
    for block in re.split(r"\n### ", sec3)[1:]:
        name = block.split("\n", 1)[0].strip()
        counts = dict.fromkeys(KINDS, 0)
        open_ids, n = [], 0
        for line in block.splitlines():
            if not line.startswith("| US-GAP-"):
                continue
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            kind = classify(cells[3] if len(cells) > 3 else "")
            counts[kind] += 1
            n += 1
            if kind == "open":
                open_ids.append(cells[0].replace("US-GAP-", ""))
        total_gaps += n
        for k in KINDS:
            totals[k] += counts[k]
        rows_out.append(f"| {name} | {n} | " + " | ".join(str(counts[k]) for k in KINDS) + " |")
        if open_ids:
            open_lines.append(f"- **{name.split(' ', 1)[0]}**: US-GAP-" + ", ".join(open_ids))
    today = datetime.date.today().isoformat()
    head = (f"### 2e. User-story gap list, pass 2 (US-GAP-100..362): status per module\n\n"
            f"Generated by `python scripts/quality/gap2_status.py` from the Outcome column of "
            f"`docs/quality/user-stories/GAP_ANALYSIS_2.md` (rebuilt after every batch; last {today}). "
            f"Partial / waiting rows keep their CLR or PENDING reference in the gap list.\n\n"
            "| Module | Gaps | Done | Partial | Waiting FCI | Blocked | Story fixed | Dropped | Open |\n"
            "|---|---|---|---|---|---|---|---|---|\n")
    total = f"| **Total** | **{total_gaps}** | " + " | ".join(f"**{totals[k]}**" for k in KINDS) + " |\n"
    opens = "\nOpen gaps by module:\n\n" + ("\n".join(open_lines) if open_lines else "- none") + "\n"
    return head + "\n".join(rows_out) + "\n" + total + opens


def main() -> int:
    body = table()
    pending = PENDING.read_text(encoding="utf8")
    block = f"{BEGIN}\n{body}{END}"
    if BEGIN in pending:
        new = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, pending, flags=re.S)
    else:
        anchor = "\n## 2b. Requirement ids waiting"
        if anchor not in pending:
            raise SystemExit("anchor '## 2b. Requirement ids waiting' not found in PENDING.md")
        new = pending.replace(anchor, "\n" + block + "\n" + anchor, 1)
    if "--check" in sys.argv:
        stale = re.sub(r"last \d{4}-\d{2}-\d{2}", "", new) != re.sub(r"last \d{4}-\d{2}-\d{2}", "", pending)
        print("gap2 status: " + ("out of date" if stale else "up to date"))
        return 1 if stale else 0
    PENDING.write_text(new, encoding="utf8", newline="\n")
    print("gap2 status written to", PENDING.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
