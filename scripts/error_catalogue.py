"""Generates docs/api/errors.md from the backend's ErrorCode enums (the single source of every code).

Usage: python scripts/error_catalogue.py          (writes the file)
       python scripts/error_catalogue.py --check  (exit 1 when the file is out of date)
"""

import io
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "backend", "src", "main", "java")
OUT = os.path.join(ROOT, "docs", "api", "errors.md")
# NAME( HttpStatus.X, "CODE", "type", "title", "detail" ) — detail may be several concatenated literals.
ENTRY = re.compile(
    r"^\s{4}([A-Z][A-Z0-9_]+)\(\s*HttpStatus\.([A-Z_]+),\s*\"([^\"]+)\",\s*\"([^\"]+)\",\s*\"([^\"]*)\",\s*((?:\"(?:[^\"\\]|\\.)*\"\s*\+?\s*)+)\)",
    re.M,
)
STATUS = {
    "BAD_REQUEST": 400, "UNAUTHORIZED": 401, "FORBIDDEN": 403, "NOT_FOUND": 404, "METHOD_NOT_ALLOWED": 405,
    "NOT_ACCEPTABLE": 406, "CONFLICT": 409, "PRECONDITION_FAILED": 412, "PAYLOAD_TOO_LARGE": 413,
    "CONTENT_TOO_LARGE": 413, "UNSUPPORTED_MEDIA_TYPE": 415, "UNPROCESSABLE_ENTITY": 422, "UNPROCESSABLE_CONTENT": 422,
    "LOCKED": 423, "PRECONDITION_REQUIRED": 428, "TOO_MANY_REQUESTS": 429, "INTERNAL_SERVER_ERROR": 500,
    "SERVICE_UNAVAILABLE": 503, "GATEWAY_TIMEOUT": 504, "BAD_GATEWAY": 502,
}


def enums():
    for d, _, files in os.walk(SRC):
        for f in files:
            if f.endswith(".java"):
                text = io.open(os.path.join(d, f), encoding="utf-8").read()
                if re.search(r"enum\s+\w+\s+implements\s+ErrorCode", text):
                    module = os.path.relpath(d, SRC).replace(os.sep, ".").replace("in.gov.fci.payroll.", "").split(".")[0]
                    yield module, f[:-5], text


def render():
    out = [
        "# API error catalogue (RFC 9457)",
        "",
        "Generated by `python scripts/error_catalogue.py` from the backend's `ErrorCode` enums. Do not edit by hand.",
        "",
        "Every error is `application/problem+json` with `type`, `title`, `status`, `detail`, `instance` and the FCI",
        "extensions `errorCode`, `messageKey` (`error.<errorCode>`, translated by the browser from its en / hi bundle),",
        "`severity` and `actionKey` (SRS-EH-1, SRS-EH-2: the corrective action `error.<errorCode>.action`, else the",
        "status's `error.action.<status>`), `args`, `correlationId`, `timestamp` and, for validation errors,",
        "`violations[]`. Severity: SECURITY for 401 / 403 / 423 and for the codes an enum names in its",
        "`SECURITY_CONDITIONS` (SRS-EH-5: an attempted history-row edit), BLOCKING for every other refusal; warnings",
        "are acknowledged where raised (C-01 Warn checks, X-05 WARNING entries), never refused. `type` is",
        "`https://errors.fci.gov.in/<type>`. Codes are `MOD-nnn-NAME`; the number is the HTTP status; each code is unique",
        "(`ErrorCodeContractTest`) except `AUTH-403-LOCATION`, shared on purpose so an unknown and a forbidden location look",
        "the same.",
        "",
    ]
    for module, name, text in sorted(enums(), key=lambda e: (e[0] != "platform", e[0], e[1])):
        out += [f"## {module} — `{name}`", "", "| errorCode | HTTP | Severity | type | Title | Detail |", "|---|---|---|---|---|---|"]
        # SRS-EH-5: codes held SECURITY against the code, whatever the status (ApiErrorCode.SECURITY_CONDITIONS).
        named = re.search(r"SECURITY_CONDITIONS\s*=\s*(?:java\.util\.)?Set\.of\(([^)]*)\)", text)
        security = set(re.findall(r"\"([^\"]+)\"", named.group(1))) if named else set()
        for m in ENTRY.finditer(text):
            detail = "".join(re.findall(r"\"((?:[^\"\\]|\\.)*)\"", m.group(6))).replace("|", "\\|")
            status = STATUS.get(m.group(2), m.group(2))
            severity = "SECURITY" if status in (401, 403, 423) or m.group(3) in security else "BLOCKING"
            out.append(f"| {m.group(3)} | {status} | {severity} | {m.group(4)} | {m.group(5)} | {detail} |")
        out.append("")
    return "\n".join(out)


def main():
    text = render()
    if "--check" in sys.argv:
        current = io.open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != text:
            print("docs/api/errors.md is out of date: run python scripts/error_catalogue.py")
            return 1
        return 0
    io.open(OUT, "w", encoding="utf-8", newline="\n").write(text)
    print(f"errors.md: {text.count(chr(10) + '| ') - text.count('| errorCode')} codes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
