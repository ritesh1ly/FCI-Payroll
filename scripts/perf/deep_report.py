#!/usr/bin/env python3
"""Writes docs/perf/module-<NN>-deep.md from a deep-profile run's outputs (load-module + JFR).

Inputs (written by scripts/perf/deep-profile.py): docs/perf/module-<NN>-load.json, -io.json, -jfr.txt.
The report states the endpoints' latency against the SLA (3 s interactive, 1 minute for a download),
the database round trips and read time per request, the online JVM's CPU, GC, allocation, exceptions,
file writes, and the H2 database JVM's hot methods; findings and fixes are added by hand below the
generated part (the marker line keeps them on regeneration).

Usage: python scripts/perf/deep_report.py 09 [01 05 ...]
"""
import json
import pathlib
import re
import sys

PERF = pathlib.Path(__file__).resolve().parents[2] / "docs" / "perf"
MARKER = "<!-- findings below are kept on regeneration -->"


def section(text, name, prefix="## "):
    m = re.search(r"^" + re.escape(prefix + name) + r"\n(.*?)(?=^## |^# |\Z)", text, re.S | re.M)
    return [l for l in (m.group(1).strip().splitlines() if m else []) if l.strip()]


def table_rows(lines, limit):
    """The data rows of a JFR view table (after the dashes line)."""
    out, started = [], False
    for l in lines:
        if set(l.strip()) <= set("- ") and l.strip():
            started = True
            continue
        if started:
            out.append(" ".join(l.split()))
        if len(out) >= limit:
            break
    return out


def report(mod):
    load = json.loads((PERF / f"module-{mod}-load.json").read_text(encoding="utf-8"))
    io = json.loads((PERF / f"module-{mod}-io.json").read_text(encoding="utf-8"))
    jfr = (PERF / f"module-{mod}-jfr.txt").read_text(encoding="utf-8")
    rows = sorted(load["rows"], key=lambda r: -r["p99"])
    total = sum(r["requests"] for r in rows)
    errors = sum(r["errors"] for r in rows)
    out = [
        f"# Module {mod}: deep profile ({load['at'][:10]})",
        "",
        "GENERATED by `python scripts/perf/deep_report.py` from the outputs of `scripts/perf/deep-profile.py` (VOLUME set,",
        "stack B, one machine: numbers to compare runs, not capacity figures). SLA (owner 2026-10-27): 3 s per interactive",
        "request, 1 minute per report / Excel download.",
        "",
        f"Load: {load['concurrency']} desks x {load['iterations']} rounds, {total:,} requests, {load['throughput']} req/s, "
        f"{errors} errors; SLA breaches: {', '.join(load.get('breaches', [])) or 'none'}.",
        "",
        "| Endpoint | Requests | Errors | p50 ms | p95 ms | p99 ms | max ms | avg bytes |",
        "|---|---|---|---|---|---|---|---|",
    ]
    out += [f"| {r['endpoint']} | {r['requests']} | {r['errors']} | {r['p50']} | {r['p95']} | {r['p99']} | {r['max']} | "
            f"{r['avgBytes']:,} |" for r in rows]
    db = io.get("database", {})
    out += [
        "",
        "## I/O",
        "",
        f"- Database (H2 TCP): {io.get('dbRoundTripsPerRequest')} round trips and {io.get('dbReadMsPerRequest')} ms of reads "
        f"per request ({db.get('SocketRead', {}).get('events', 0):,} reads, {db.get('SocketRead', {}).get('bytes', 0):,} bytes in).",
    ]
    for line in table_rows(section(jfr, "file-writes-by-path"), 3):
        out.append(f"- File writes: {line}")
    gc = [l.strip() for l in section(jfr, "gc-pauses") if l.startswith(("Total Pause", "Number of", "Maximum"))]
    cpu = [l.strip() for l in section(jfr, "cpu-load") if "Average" in l]
    exc = [l.strip() for l in section(jfr, "exception-count") if "Thrown" in l]
    out += ["", "## Online JVM", "", f"- CPU: {'; '.join(cpu)}", f"- GC: {'; '.join(gc)}", f"- {'; '.join(exc)}"]
    for line in table_rows(section(jfr, "exception-by-type"), 4):
        out.append(f"  - {line}")
    out += ["- Hot methods (samples):"]
    out += [f"  - {l}" for l in table_rows(section(jfr, "hot-methods"), 6)]
    out += ["- Allocation by class:"]
    out += [f"  - {l}" for l in table_rows(section(jfr, "allocation-by-class"), 5)]
    h2 = table_rows(section(jfr, "h2 hot-methods"), 6)
    if h2:
        out += ["", "## H2 database JVM", "", "- Hot methods (samples):"] + [f"  - {l}" for l in h2]
        h2cpu = [l.strip() for l in section(jfr, "h2 cpu-load") if "Average" in l]
        out += [f"- CPU: {'; '.join(h2cpu)}"]
    target = PERF / f"module-{mod}-deep.md"
    kept = ""
    if target.exists() and MARKER in target.read_text(encoding="utf-8"):
        kept = target.read_text(encoding="utf-8").split(MARKER, 1)[1]
    out += ["", MARKER]
    target.write_text("\n".join(out) + (kept if kept else "\n\n## Findings\n\n- (none recorded)\n"), encoding="utf-8")
    print(f"wrote {target}")


if __name__ == "__main__":
    for m in sys.argv[1:]:
        report(m)
