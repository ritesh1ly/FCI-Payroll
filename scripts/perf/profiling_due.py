#!/usr/bin/env python3
"""Which modules need profiling again, from docs/perf/profiling-tracker.json; regenerates PROFILING_TRACKER.md.

Incremental profiling (owner 2026-10-27): a module is DUE for a kind of pass ('shallow' or 'deep') when it has never
had one, or when a file under its paths changed after the commit of its latest pass of that kind (committed changes
since that commit, plus uncommitted changes in the working tree). A pass measured on an uncommitted working tree
("worktree": true) counts from its commit; set the commit of the pass to the commit that holds the measured code when
it is committed.

Usage:
  python scripts/perf/profiling_due.py              # table of every module + the due list; rewrites the Markdown
  python scripts/perf/profiling_due.py --kind deep  # due for a deep pass only
  python scripts/perf/profiling_due.py --check      # exit 1 when any module is due (for a checklist)
"""
import argparse
import json
import pathlib
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[2]
TRACKER = ROOT / "docs" / "perf" / "profiling-tracker.json"
MARKDOWN = ROOT / "docs" / "perf" / "PROFILING_TRACKER.md"


def git(*args):
    r = subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, encoding="utf-8", errors="replace")
    return r.stdout.strip() if r.returncode == 0 else None


def changed_since(commit, paths):
    """Files under paths changed after commit (committed and uncommitted); None when the commit is unknown."""
    if git("cat-file", "-e", f"{commit}^{{commit}}") is None:
        return None
    committed = git("diff", "--name-only", f"{commit}..HEAD", "--", *paths) or ""
    dirty = git("status", "--porcelain", "--", *paths) or ""
    files = {f for f in committed.splitlines() if f}
    files |= {line[3:] for line in dirty.splitlines() if len(line) > 3}
    return sorted(files)


def latest(module, kind):
    """The latest pass of the kind; a deep pass also stands for a shallow one (it measures more)."""
    wanted = {"shallow": ("shallow", "deep"), "deep": ("deep",)}[kind]
    passes = [p for p in module["passes"] if p["kind"] in wanted]
    return max(passes, key=lambda p: p["date"]) if passes else None


def status(module, kind):
    p = latest(module, kind)
    if p is None:
        return "DUE (never)", []
    changed = changed_since(p["commit"], module["paths"])
    if changed is None:
        return f"DUE (commit {p['commit']} unknown)", []
    if p.get("worktree"):
        # Measured on uncommitted code: only changes committed after it would count, and its own edits are in
        # the working tree; treat it as current until it is committed with the real commit recorded.
        committed = git("diff", "--name-only", f"{p['commit']}..HEAD", "--", *module["paths"]) or ""
        changed = sorted(f for f in committed.splitlines() if f)
    return ("DUE (%d files changed since %s)" % (len(changed), p["commit"]) if changed else "current"), changed


def kinds_all(a):
    return ["performance"] if a.kind in (None, "performance") else []


def fmt(v):
    return "-" if v is None else (f"{v:,}" if isinstance(v, int) else str(v))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--kind", choices=["shallow", "deep", "performance"])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    data = json.loads(TRACKER.read_text(encoding="utf-8"))
    kinds = [a.kind] if a.kind in ("shallow", "deep") else ([] if a.kind else ["shallow", "deep"])
    md = [
        "# Profiling and performance tracker (module by module)",
        "",
        "GENERATED by `python scripts/perf/profiling_due.py` from `docs/perf/profiling-tracker.json` (edit the JSON, "
        "not this file). Owner 2026-10-27: profiling is incremental: a module is profiled again only when its code "
        "changed after the commit of its last pass, or it has never had the pass.",
        "",
    ]
    for k, text in data["kinds"].items():
        md.append(f"- **{k}**: {text}")
    md += [
        "",
        "| Module | Name | Last shallow | Last deep | Shallow status | Deep status | Worst p99 (deep, else shallow) | DB trips / ms per request | Open |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    due = []
    for m in data["modules"]:
        shallow = [p for p in m["passes"] if p["kind"] == "shallow"]
        s = max(shallow, key=lambda p: p["date"]) if shallow else None
        d = latest(m, "deep")
        st = {k: status(m, k) for k in ("shallow", "deep")}
        for k in kinds:
            if st[k][0] != "current":
                due.append((m["module"], k, st[k][0]))
        best = d or s
        worst = f"{fmt(best['worstP99Ms'])} ms ({best['worstEndpoint']})" if best else "-"
        io = f"{fmt(d.get('dbRoundTripsPerRequest'))} / {fmt(d.get('dbReadMsPerRequest'))}" if d else "-"
        md.append(
            f"| {m['module']} | {m['name']} | {s['date'] + ' @' + s['commit'] if s else '-'} | "
            f"{d['date'] + ' @' + d['commit'] + (' (worktree)' if d.get('worktree') else '') if d else '-'} | "
            f"{st['shallow'][0]} | {st['deep'][0]} | {worst} | {io} | {'; '.join(m.get('open', [])) or '-'} |"
        )
    md += ["", "## Performance tests", "", data.get("performanceDefinition", ""), "",
           "| Date | Commit | Base | Modules | Stages (users: req/s, p99 ms, errors %) | Stress (req/s, p99 ms, errors %) | SLA breaches | Status | Findings |",
           "|---|---|---|---|---|---|---|---|---|"]
    runs = sorted(data.get("performance", []), key=lambda r: r["date"])
    for r in runs:
        mods = [m for m in data["modules"] if m["module"] in r["modules"]]
        changed = set()
        for m in mods:
            c = changed_since(r["commit"], m["paths"]) if not r.get("worktree") else (
                git("diff", "--name-only", f"{r['commit']}..HEAD", "--", *m["paths"]) or "").splitlines()
            changed |= set(c or [])
        st = "current" if not changed else f"DUE ({len(changed)} files changed)"
        if r is runs[-1] and st != "current" and "performance" in kinds_all(a):
            due.append(("perf", "performance", st))
        stages = "; ".join(f"{s['users']}: {s['throughput']}/s, {s['p99']}, {s['errorRate']}" for s in r["stages"])
        stress = r.get("stress")
        md.append(f"| {r['date']} | {r['commit']}{' (worktree)' if r.get('worktree') else ''} | {r['base']} | "
                  f"{', '.join(r['modules'])} | {stages} | "
                  f"{(str(stress['throughput']) + '/s, ' + str(stress['p99']) + ', ' + str(stress['errorRate'])) if stress else '-'} | "
                  f"{r.get('slaBreaches', '-')} | {st} | {'; '.join(r.get('findings', [])) or '-'} |")
    if not runs:
        md.append("| - | - | - | - | none yet | - | - | DUE | - |")
        if "performance" in kinds_all(a):
            due.append(("perf", "performance", "DUE (never)"))
    md += ["", "## Findings by pass", ""]
    for m in data["modules"]:
        for p in sorted(m["passes"], key=lambda p: p["date"]):
            for f in p.get("findings", []):
                md.append(f"- {m['module']} ({p['kind']} {p['date']}): {f}")
    md += ["", "## How to run the next pass", "",
           "1. `python scripts/perf/profiling_due.py --kind deep` lists the modules due.",
           "2. Deploy stack B (`deploy-local.ps1 ... -Volume` for deep), then per module "
           "`python scripts/perf/deep-profile.py --module NN` (25 region desks: `--concurrency 25 --think 120`; "
           "HQ desks: `--concurrency 2 --iterations 150 --think 20`) and the browser profile "
           "(`cd frontend; PERF_MODULE=NN npx playwright test -c perf/playwright.perf.config.ts`, with the E2E environment of the stack).",
           "3. Add a pass to the module in `profiling-tracker.json` (date, commit, numbers, reports, findings) and "
           "re-run this script; record fixes in the developer playbook and open items in PENDING.", ""]
    MARKDOWN.write_text("\n".join(md) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(md[6:6 + len(data["modules"]) + 2]))
    print("\nDue:" if due else "\nNothing due.")
    for mod, kind, why in due:
        print(f"  {mod} {kind}: {why}")
    raise SystemExit(1 if a.check and due else 0)


if __name__ == "__main__":
    main()
