#!/usr/bin/env node
/**
 * Build-time bundle conversion (FCILekha i18n rule). The single source of the user-interface labels
 * is backend/src/main/resources/i18n/messages_{en,hi}.properties (UTF-8), which the backend also serves
 * at /api/i18n/{locale}. This script converts both into src/generated/messages.ts so that the
 * static export renders labels on first paint, and fails if the key sets differ.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseProperties } from './build-i18n-lib.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(root, '..', 'backend', 'src', 'main', 'resources', 'i18n');
const target = join(root, 'src', 'generated', 'messages.ts');

const bundles = {};
for (const locale of ['en', 'hi']) {
  bundles[locale] = parseProperties(readFileSync(join(source, `messages_${locale}.properties`), 'utf8'));
}
const en = Object.keys(bundles.en).sort();
const hi = Object.keys(bundles.hi).sort();
const missing = [
  ...en.filter((k) => !(k in bundles.hi)).map((k) => `hi lacks ${k}`),
  ...hi.filter((k) => !(k in bundles.en)).map((k) => `en lacks ${k}`),
];
if (missing.length > 0) {
  console.error(
    'build-i18n: messages_en and messages_hi must have identical keys:\n  ' + missing.join('\n  '),
  );
  process.exit(1);
}
mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  [
    '// GENERATED by scripts/build-i18n.mjs from backend/src/main/resources/i18n. Do not edit.',
    `export const messages = ${JSON.stringify(bundles, null, 2)} as const;`,
    'export type Locale = keyof typeof messages;',
    'export type MessageKey = keyof (typeof messages)["en"];',
    '',
  ].join('\n'),
  'utf8',
);
console.log(`build-i18n: ${en.length} keys x 2 locales -> src/generated/messages.ts`);
